import pandas as pd
import torch
from tqdm import tqdm


def eval_dataset(model, dataset, ensemble=20, batch_size=10000, device="cuda"):
    """Run StaB-ddG inference over a PPI dataset and return a prediction DataFrame.

    Faithful port of ``skempi_eval.py``'s ``eval()`` loop.

    Returns a DataFrame with columns ``#Pdb, Mutation, ddG, Prediction`` (one row
    per mutation, concatenated across interfaces).  ``write_csv`` renames
    ``Prediction`` -> ``ddG_pred`` to match the original output format.
    """
    pred_df = []
    for sample in tqdm(dataset, desc="Interface"):
        complex, binder1, binder2 = sample["complex"], sample["binder1"], sample["binder2"]
        complex_mut_seqs = sample["complex_mut_seqs"].to(device)
        binder1_mut_seqs = sample["binder1_mut_seqs"].to(device)
        binder2_mut_seqs = sample["binder2_mut_seqs"].to(device)
        ddG = sample["ddG"]

        binding_ddG_pred_ensemble = []
        for _ in range(ensemble):
            with torch.no_grad():
                N = complex_mut_seqs.shape[0]
                # convert token budget to number of sequences per batch.
                # max(1,...) guard: a complex with L > batch_size (e.g. the L=3397
                # train complex) gives M=0 -> range(0,N,0) ValueError. Force >=1.
                M = max(1, batch_size // complex_mut_seqs.shape[1])

                binding_ddG_pred_ = []
                for batch_idx in range(0, N, M):
                    B = min(N - batch_idx, M)
                    batch_binding_ddG_pred = model(
                        complex, binder1, binder2,
                        complex_mut_seqs[batch_idx:batch_idx + B],
                        binder1_mut_seqs[batch_idx:batch_idx + B],
                        binder2_mut_seqs[batch_idx:batch_idx + B],
                    )
                    binding_ddG_pred_.append(batch_binding_ddG_pred.cpu().detach())

                binding_ddG_pred_ = torch.cat(binding_ddG_pred_)
                binding_ddG_pred_ensemble.append(binding_ddG_pred_.squeeze().cpu())

        binding_ddG_pred = torch.stack(binding_ddG_pred_ensemble).mean(dim=0)

        name, mutations = sample["name"], sample["mutation_list"]
        data = {
            "#Pdb": [name] * len(mutations),  # Repeat the name for all rows
            "Mutation": mutations,
            "ddG": ddG.cpu().detach().numpy(),
            "Prediction": binding_ddG_pred.cpu().detach().numpy().reshape(-1),
        }

        pred_df.append(pd.DataFrame(data))

    pred_df = pd.concat(pred_df, ignore_index=True)
    return pred_df


def write_csv(pred_df, out_csv):
    """Write predictions to ``out_csv`` in the EXACT original ``skempi_eval.py`` format.

    Mirrors skempi_eval.py:123-126:

        combined_df = pred_df[['#Pdb', 'Mutation', 'ddG']]
        combined_df['ddG_pred'] = pred_df['Prediction']
        combined_df.to_csv(out_csv)   # NOTE: no index=False

    Produces a header line ``,#Pdb,Mutation,ddG,ddG_pred`` (leading unnamed index
    column) and the RAW prediction (no x-1).
    """
    combined_df = pred_df[["#Pdb", "Mutation", "ddG"]].copy()
    combined_df["ddG_pred"] = pred_df["Prediction"].to_numpy()
    combined_df.to_csv(out_csv)
    return combined_df


# --------------------------------------------------------------------------- #
# CLI: evaluate a FINETUNED backbone checkpoint on a SKEMPI split.             #
#                                                                              #
#     python -m run.eval --backbone {mpnn,esmc_600m,esmc_6b,esm3} \            #
#         --checkpoint <ft.pt> --out <csv> [--split {test,train}] \            #
#         [--ensemble 1] [--device cuda] [--limit K] \                         #
#         [--pdb_dir data/SKEMPI2_PDBs]                                        #
#                                                                              #
# Mirrors run/lr_sweep.py's eval path EXACTLY: build the SKEMPI split dataset, #
# build a fresh scorer, load the finetuned backbone weights, wrap in StaBddG,  #
# run eval_dataset, write_csv in the baseline format.                          #
# --------------------------------------------------------------------------- #

# SKEMPI split inputs (resolved against the worktree root, cwd-independent;
# same paths lr_sweep.py / finetune.py use). pdb_dir is overridable via --pdb_dir.
_SKEMPI_CSV = str(_WORKTREE_ROOT / "data/SKEMPI/filtered_skempi.csv")
_SKEMPI_TEST_SPLIT = str(_WORKTREE_ROOT / "data/SKEMPI/test_pdb.pkl")
_SKEMPI_TRAIN_SPLIT = str(_WORKTREE_ROOT / "data/SKEMPI/train_pdb.pkl")
_SKEMPI_PDB_DIR = str(_WORKTREE_ROOT / "data/SKEMPI2_PDBs")

# Per-split (split path, structure-dict cache path). The cache path mirrors the
# build paths used elsewhere (finetune.py uses cache/skempi_train_pdb_dict.pkl
# for train; eval historically used cache/skempi_test_pdb_dict.pkl for test).
_SKEMPI_SPLITS = {
    "test": (_SKEMPI_TEST_SPLIT, "cache/skempi_test_pdb_dict.pkl"),
    "train": (_SKEMPI_TRAIN_SPLIT, "cache/skempi_train_pdb_dict.pkl"),
}

# Evaluation token budget per backbone (no-grad, larger than finetune); mirrors
# run/lr_sweep.py::EVAL_BATCH_SIZE.
_EVAL_BATCH_SIZE = {
    "mpnn": 10000,
    "esmc_600m": 10000,
    "esmc_6b": 10000,
    "esm3": 2000,
    "esm3_stab": 2000,
}


def _build_eval_dataset(pdb_dir, split="test", limit=None):
    """Build a SKEMPI split dataset (``test`` or ``train``; optionally first K).

    Mirrors run/lr_sweep.py::_build_eval_dataset (same csv / cache convention);
    ``split`` selects the test vs train split path (and matching cache). Building
    the train split lets us measure TRAIN fit (does the model fit the training
    data?) vs the default TEST generalization.
    """
    from stabddg.ppi_dataset import SKEMPIDataset

    split_path, cache_path = _SKEMPI_SPLITS[split]
    dataset = SKEMPIDataset(
        csv_path=_SKEMPI_CSV,
        split_path=split_path,
        pdb_dir=pdb_dir,
        pdb_dict_cache_path=cache_path,
        af_apo_structures=False,
    )
    if limit is not None:
        dataset.data = dataset.data[:limit]
    return dataset


def main():
    import argparse

    from common.build_scorer import build_scorer
    from common.stab_model import StaBddG
    # _load_checkpoint_for_esm: build_scorer only honours --checkpoint for the
    # `mpnn` backbone; for esm3/esmc the factory ignores it, so the finetuned
    # backbone weights are loaded into scorer.backbone_module AFTER the build
    # (no-op for mpnn / when checkpoint is None) — exactly as finetune.py does.
    from run.finetune import _load_checkpoint_for_esm

    ap = argparse.ArgumentParser(
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
        description="Evaluate a finetuned backbone checkpoint on the SKEMPI test split.",
    )
    ap.add_argument("--backbone", required=True,
                    choices=["mpnn", "esmc_600m", "esmc_6b", "esm3", "esm3_stab"])
    ap.add_argument("--checkpoint", type=str, required=True,
                    help="finetuned backbone state_dict (mpnn: StaB-ddG ckpt; "
                         "esm*: consolidated/per-epoch backbone state_dict)")
    ap.add_argument("--out", type=str, required=True, help="output CSV path")
    ap.add_argument("--split", type=str, default="test", choices=["test", "train"],
                    help="SKEMPI split to evaluate: test (generalization, default) "
                         "or train (measure training-set fit)")
    ap.add_argument("--ensemble", type=int, default=1, help="eval ensemble size")
    ap.add_argument("--batch_size", type=int, default=None,
                    help="TOKEN budget per forward (default: per-backbone)")
    ap.add_argument("--device", type=str, default="cuda")
    ap.add_argument("--limit", type=int, default=None,
                    help="first K eval complexes (smoke)")
    ap.add_argument("--pdb_dir", type=str, default=_SKEMPI_PDB_DIR,
                    help="SKEMPI PDB directory")
    args = ap.parse_args()

    device = (torch.device("cuda" if torch.cuda.is_available() else "cpu")
              if args.device == "cuda" else torch.device(args.device))
    batch_size = args.batch_size or _EVAL_BATCH_SIZE.get(args.backbone, 10000)

    # Build a fresh scorer. For `mpnn`, build_scorer loads --checkpoint directly;
    # for esm3/esmc it ignores it, so we load the finetuned weights afterwards.
    scorer = build_scorer(
        args.backbone,
        device=str(device),
        checkpoint=args.checkpoint,
        pdb_dir=args.pdb_dir,
    )
    _load_checkpoint_for_esm(scorer, args.backbone, args.checkpoint)
    scorer.to(device)

    model = StaBddG(scorer).to(device).eval()
    dataset = _build_eval_dataset(args.pdb_dir, split=args.split, limit=args.limit)

    print(f"[eval] backbone={args.backbone} ckpt={args.checkpoint} "
          f"split={args.split} complexes={len(dataset)} ensemble={args.ensemble} "
          f"batch_size(tokens)={batch_size} device={device}", flush=True)

    with torch.no_grad():
        pred_df = eval_dataset(model, dataset, ensemble=args.ensemble,
                               batch_size=batch_size, device=str(device))

    out_dir = os.path.dirname(args.out)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    write_csv(pred_df, args.out)
    print(f"[eval] wrote {args.out} ({len(pred_df)} rows)", flush=True)


if __name__ == "__main__":
    main()
