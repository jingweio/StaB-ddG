"""
eval.py — backbone-agnostic SKEMPI evaluation loop.

This is a faithful port of the original ``skempi_eval.py`` ``eval()`` loop
(skempi_eval.py:12-65), generalised to take a *prebuilt*
:class:`common.stab_model.StaBddG` model (any backbone) rather than constructing
a ProteinMPNN-specific one inside the loop.

``eval_dataset`` reproduces the per-interface ensembling and token-budget
batching of the original.  ``write_csv`` reproduces the original CSV output
(skempi_eval.py:122-126) EXACTLY, including:

  - columns ``#Pdb, Mutation, ddG, ddG_pred`` (predictions stored as ``ddG_pred``),
  - the leading *unnamed* pandas index column — the original calls ``to_csv``
    WITHOUT ``index=False``, producing a header line ``,#Pdb,Mutation,ddG,ddG_pred``,
  - the RAW prediction with NO sign flip.

Sign convention
----------------
The original ``skempi_eval.py`` stores the raw ``binding_ddG_pred`` (skempi_eval.py:48)
and does NOT multiply by -1 (only the separate ``run_stabddg.py:37`` applies x-1).
The reproduced baseline CSV
``ibex_records/stab-ddg_repro/eval_skempi_ft_47437925.csv`` was generated by
``skempi_eval.py`` and is positively correlated with the ground-truth ``ddG``
(Spearman 0.531) — confirming NO x-1 in eval.  We mirror that here.
"""

